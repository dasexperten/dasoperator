// =============================================================================
// Сторож обвала заказов на витрине .ru
//
// Зачем он есть. 18.06.2026 отвалилась реклама: трафик упал с 430 визитов в
// сутки до 89, заказы — с 15 в день до одного. Никто не заметил 75 дней,
// потому что здоровье системы мерилось техникой: жива ли касса, есть ли ключи.
// Касса была жива всё это время и честно отвечала «всё хорошо». Упущено около
// 1,2 млн рублей выручки. Этот файл сторожит не технику, а факт продаж.
//
// Как считает. Раз в сутки берём вчерашний полный день и сравниваем со средним
// за 14 предыдущих дней. Меньше трети среднего — сигнал в Telegram.
// Треть, а не половина: обычный разброс по дням в мае был от 16 до 46 заказов
// при среднем 26, то есть до 60% вниз — норма. Обвал 18 июня был до 7%.
// Порог в треть отделяет одно от другого и не будит по выходным.
//
// Почему требуется база не меньше 3 заказов в день. На малых числах отношение
// шумит: один заказ вместо двух — это «падение вдвое», но не событие. Пока
// витрина не вернётся к живому обороту, сторож молчит осознанно и говорит об
// этом в отчёте, а не притворяется, что всё проверил.
//
// Дедуп. Один сигнал в 20 часов, отметка лежит в crm_sync_state. Иначе при
// длинном обвале Владелец получал бы одно и то же письмо каждое утро и через
// неделю перестал бы их читать — а это ровно та слепота, от которой сторож.
// =============================================================================

import type { Env } from '../types';

const ОКНО_ДНЕЙ = 14;          // с чем сравниваем вчерашний день
const ПОРОГ = 1 / 3;           // ниже трети среднего — сигнал
const МИНИМУМ_БАЗЫ = 3;        // среднее меньше — молчим, чисел не хватает
const ПАУЗА_МЕЖДУ_СИГНАЛАМИ = 20 * 3600;
const КЛЮЧ_ОТМЕТКИ = 'orders_drop:last_alert_at';

export interface РезультатСторожа {
  проверено_за: string;        // дата вчерашнего дня, YYYY-MM-DD
  вчера: number;               // заказов вчера
  среднее: number;             // среднее за 14 предыдущих дней
  порог: number;               // при скольки заказах сигналим
  сигнал: boolean;
  причина: string;             // человеческая, уходит в лог крона
}

/** Дата в московском дне: витрина отдаёт created_at со смещением +03:00. */
function деньМосквы(сдвигДней: number): string {
  const t = new Date(Date.now() + 3 * 3600 * 1000 - сдвигДней * 86400 * 1000);
  return t.toISOString().slice(0, 10);
}

async function читатьОтметку(env: Env): Promise<number> {
  const row = await env.DB
    .prepare('SELECT value FROM crm_sync_state WHERE key = ?1')
    .bind(КЛЮЧ_ОТМЕТКИ)
    .first<{ value: string }>();
  const n = Number(row?.value ?? 0);
  return Number.isFinite(n) ? n : 0;
}

async function писатьОтметку(env: Env, ts: number): Promise<void> {
  await env.DB
    .prepare(`INSERT INTO crm_sync_state (key, value, updated_at) VALUES (?1, ?2, ?3)
              ON CONFLICT(key) DO UPDATE SET value = ?2, updated_at = ?3`)
    .bind(КЛЮЧ_ОТМЕТКИ, String(ts), ts)
    .run();
}

async function послатьВTelegram(env: Env, текст: string): Promise<void> {
  const secret = env.TELEGRAMER_BRIDGE_SECRET;
  if (!secret) {
    console.warn('[orders-drop] TELEGRAMER_BRIDGE_SECRET не задан, сигнал не ушёл');
    return;
  }
  try {
    const resp = await fetch('https://telegramer-bridge.dasexperten.workers.dev/send', {
      method: 'POST',
      headers: { Authorization: `Bearer ${secret}`, 'Content-Type': 'application/json' },
      body: JSON.stringify({ to: 'me', text: текст, first_message_confirmation: 'ok' }),
    });
    if (!resp.ok) {
      console.warn(`[orders-drop] Telegram HTTP ${resp.status}: ${(await resp.text()).slice(0, 200)}`);
    }
  } catch (e) {
    console.warn('[orders-drop] Telegram не ответил:', e);
  }
}

export async function runOrdersDropWatchdog(env: Env): Promise<РезультатСторожа> {
  const вчера = деньМосквы(1);
  const началоОкна = деньМосквы(1 + ОКНО_ДНЕЙ);

  // Считаем по дням витрины. Берём все заказы, не только оплаченные: если
  // сломался приём оплаты, заказы ещё создаются — это другая беда, её ловит
  // другой сторож. Здесь важно, что люди перестали доходить до корзины.
  const { results } = await env.DB
    .prepare(`SELECT substr(created_at, 1, 10) AS d, COUNT(*) AS n
              FROM crm_orders_ru
              WHERE substr(created_at, 1, 10) >= ?1 AND substr(created_at, 1, 10) <= ?2
              GROUP BY d`)
    .bind(началоОкна, вчера)
    .all<{ d: string; n: number }>();

  const поДням = new Map<string, number>();
  for (const r of results ?? []) поДням.set(r.d, Number(r.n) || 0);

  const заказовВчера = поДням.get(вчера) ?? 0;

  // Дни без единого заказа в карте отсутствуют — их нужно считать нулями,
  // иначе среднее посчитается только по удачным дням и завысит норму.
  let сумма = 0;
  for (let i = 2; i <= 1 + ОКНО_ДНЕЙ; i++) сумма += поДням.get(деньМосквы(i)) ?? 0;
  const среднее = сумма / ОКНО_ДНЕЙ;
  const порог = среднее * ПОРОГ;

  const итог: РезультатСторожа = {
    проверено_за: вчера,
    вчера: заказовВчера,
    среднее: Math.round(среднее * 10) / 10,
    порог: Math.round(порог * 10) / 10,
    сигнал: false,
    причина: '',
  };

  if (среднее < МИНИМУМ_БАЗЫ) {
    итог.причина = `база мала: ${итог.среднее} заказов в день за ${ОКНО_ДНЕЙ} дней, нужно от ${МИНИМУМ_БАЗЫ}`;
    return итог;
  }
  if (заказовВчера >= порог) {
    итог.причина = `норма: ${заказовВчера} при пороге ${итог.порог}`;
    return итог;
  }

  const сейчас = Math.floor(Date.now() / 1000);
  const прошлыйСигнал = await читатьОтметку(env);
  if (сейчас - прошлыйСигнал < ПАУЗА_МЕЖДУ_СИГНАЛАМИ) {
    итог.причина = `обвал есть, но сигнал уже был ${Math.round((сейчас - прошлыйСигнал) / 3600)} ч назад`;
    return итог;
  }

  const падение = среднее > 0 ? Math.round((1 - заказовВчера / среднее) * 100) : 100;
  await послатьВTelegram(
    env,
    `🔻 Заказы на dasexperten.ru обвалились\n\n` +
    `Вчера (${вчера}): ${заказовВчера} заказов\n` +
    `Обычно: ${итог.среднее} в день за последние ${ОКНО_ДНЕЙ} дней\n` +
    `Падение: ${падение}%\n\n` +
    `Проверить в таком порядке:\n` +
    `1. Яндекс.Директ — баланс, статус кампаний, модерация\n` +
    `2. Метрика, счётчик 107720199 — упал трафик или упала конверсия\n` +
    `3. Сама витрина — открывается ли, работает ли корзина\n\n` +
    `18.06.2026 такой же обвал заметили через 75 дней и потеряли ~1,2 млн ₽.`,
  );
  await писатьОтметку(env, сейчас);

  итог.сигнал = true;
  итог.причина = `обвал ${падение}%: ${заказовВчера} против ${итог.среднее}`;
  return итог;
}
