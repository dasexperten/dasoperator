-- 0083 — связка обезличенного ключа витрины .ru со счётом лояльности.
-- Владелец 02.09.2026: разрешил разовый обход витрины, чтобы в графе Balance
-- появились остатки. Причина: счёт заведён на телефон, лента отдаёт
-- необратимый ключ, соединять их было нечем — 0 совпадений из 1482.
--
-- В таблице лежит только ключ и номер счёта. Телефон здесь не хранится: он
-- нужен на миг, чтобы найти счёт, и дальше выбрасывается. Строка со
-- account_id IS NULL значит «спросили, счёта нет» — чтобы не спрашивать снова.
--
-- Откат: DROP TABLE crm_loyalty_key_map. Экран вернётся к прочеркам, ничего
-- другого не пострадает — таблица только выводная.
CREATE TABLE IF NOT EXISTS crm_loyalty_key_map (
  customer_key TEXT PRIMARY KEY,
  account_id   TEXT,
  checked_at   INTEGER NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_loyalty_key_map_account
  ON crm_loyalty_key_map(account_id);
